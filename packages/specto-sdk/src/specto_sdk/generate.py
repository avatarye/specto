"""Generate the typed SDK surface from ``api-info.json`` (contracts section 14).

``tools/gen_api.py`` runs ``main()``: it exports ``api-info.json`` from a fresh
``Engine`` (every built-in command) and renders ``specto_sdk/_api.py``, one keyword-only
method per command. Both files are checked in; ``test_generated.py`` fails when they
drift from the registry.
"""

from __future__ import annotations

import json
import keyword
from pathlib import Path
from typing import Any

PKG_DIR = Path(__file__).resolve().parent
API_INFO_PATH = PKG_DIR / "api-info.json"
API_MODULE_PATH = PKG_DIR / "_api.py"

HEADER = '''"""GENERATED by tools/gen_api.py from api-info.json. Do not edit.

One method per command; keyword-only arguments mirror the command's ``Args`` model.
Arguments left at ``UNSET`` are not sent, so the server applies its own defaults.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any{literal}

if TYPE_CHECKING:
    from .client import Client


class _Unset:
    def __repr__(self) -> str:
        return "UNSET"


UNSET: Any = _Unset()


def _args(**kw: Any) -> dict[str, Any]:
    return {k: v for k, v in kw.items() if v is not UNSET}


class Api:
    """Typed calls over a ``Client``. ``client.api.canvas_submit(document=..., label=...)``."""

    api_level = {api_level}

    def __init__(self, client: Client) -> None:
        self._client = client

    def _call(self, name: str, args: dict[str, Any]) -> dict[str, Any]:
        return self._client.call(name, args)

'''


def _q(v: Any) -> str:
    """Double-quoted literal (what ruff format wants) for strings; repr otherwise."""
    return json.dumps(v) if isinstance(v, str) else repr(v)


def method_name(command: str) -> str:
    """``canvas.submit`` -> ``canvas_submit``; ``list_commands`` stays."""
    return command.replace(".", "_").replace("-", "_")


def param_name(prop: str) -> str:
    return prop + "_" if keyword.iskeyword(prop) else prop


def annotation(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    """A readable Python annotation for a JSON-schema property."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        target = defs.get(name, {})
        return (
            "dict[str, Any]"
            if target.get("type", "object") == "object"
            else annotation(target, defs)
        )
    if "enum" in schema:
        return "Literal[" + ", ".join(_q(v) for v in schema["enum"]) + "]"
    if "const" in schema:
        return f"Literal[{_q(schema['const'])}]"
    if "anyOf" in schema:
        parts = []
        for alt in schema["anyOf"]:
            a = annotation(alt, defs)
            if a not in parts:
                parts.append(a)
        return " | ".join(parts)
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(annotation({**schema, "type": x}, defs) for x in t)
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return f"list[{annotation(schema.get('items') or {}, defs)}]"
    if t == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"dict[str, {annotation(extra, defs)}]"
        return "dict[str, Any]"
    return "Any"


def _fold(text: str, indent: str, width: int = 96) -> list[str]:
    words, lines, cur = text.split(), [], indent
    for w in words:
        if len(cur) + len(w) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent + w
        else:
            cur = cur + ("" if cur == indent else " ") + w
    if cur.strip():
        lines.append(cur.rstrip())
    return lines


def render_method(cmd: dict[str, Any]) -> str:
    schema = cmd.get("args_schema") or {}
    defs = schema.get("$defs", {})
    props: dict[str, Any] = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    params: list[str] = []
    passes: list[str] = []
    doc_args: list[str] = []
    # required first, then optional
    ordered = [p for p in props if p in required] + [p for p in props if p not in required]
    for prop in ordered:
        ps = props[prop]
        ann = annotation(ps, defs)
        pn = param_name(prop)
        if prop in required:
            params.append(f"{pn}: {ann}")
        else:
            params.append(f"{pn}: {ann} = UNSET")
        # a keyword-named property (``from``) is passed through a dict: ``from=`` is not Python
        passes.append(f"{prop}={pn}" if pn == prop else f"**{{{_q(prop)}: {pn}}}")
        d = ps.get("description")
        dflt = f" (default {ps['default']!r})" if "default" in ps else ""
        doc_args.append(f"{prop}: {ann}{dflt}" + (f" -- {d}" if d else ""))
    name = method_name(cmd["name"])
    sig = ["self"]
    if params:
        sig.append("*")
        sig.extend(params)
    one_line = f"    def {name}({', '.join(sig)}) -> dict[str, Any]:"
    if len(one_line) <= 100:
        lines = [one_line]
    else:
        lines = [f"    def {name}(", *(f"        {s}," for s in sig), "    ) -> dict[str, Any]:"]
    doc = (cmd.get("doc") or cmd["name"]).strip()
    flags = []
    if cmd.get("read_only"):
        flags.append("read-only")
    if cmd.get("destructive"):
        flags.append("destructive")
    if cmd.get("effects"):
        flags.append("effects: " + ", ".join(cmd["effects"]))
    body_doc = _fold(doc + (f" [{'; '.join(flags)}]" if flags else ""), "        ")
    if not doc_args and len(body_doc) == 1 and len(body_doc[0]) + 6 <= 100:
        lines.append('        """' + body_doc[0].strip() + '"""')
    else:
        lines.append('        """' + body_doc[0].strip())
        lines.extend(body_doc[1:])
        if doc_args:
            lines.append("")
            lines.append("        Args:")
            for a in doc_args:
                lines.extend(_fold(a, "            "))
        lines.append('        """')
    call_args = "_args(" + ", ".join(passes) + ")" if passes else "{}"
    stmt = f"        return self._call({_q(cmd['name'])}, {call_args})"
    if len(stmt) <= 100:
        lines.append(stmt)
    else:
        lines.append("        return self._call(")
        lines.append(f"            {_q(cmd['name'])},")
        if len(call_args) + 13 <= 100:
            lines.append(f"            {call_args},")
        else:
            lines.append("            _args(")
            lines.extend(f"                {p}," for p in passes)
            lines.append("            ),")
        lines.append("        )")
    return "\n".join(lines)


def render_api(api_info: dict[str, Any]) -> str:
    methods = [render_method(cmd) for cmd in api_info["commands"]]
    literal = ", Literal" if any("Literal[" in m for m in methods) else ""
    head = HEADER.replace("{api_level}", str(api_info.get("api_level", 1)))
    out = [head.replace("{literal}", literal).rstrip("\n")]
    for m in methods:
        out.append("")
        out.append(m)
    return "\n".join(out) + "\n"


# Modules that register commands on import, in the order the app loads them. The
# generated SDK covers what a running app serves, so every provider is imported here.
COMMAND_PROVIDERS = ("specto_intake", "specto_app.commands")


def export_api_info() -> dict[str, Any]:
    import importlib

    from specto_core import Engine

    for mod in COMMAND_PROVIDERS:
        try:
            importlib.import_module(mod)
        except ModuleNotFoundError as exc:
            if exc.name is None or not mod.startswith(exc.name):
                raise
    return Engine(project=None).api_info()


def load_bundled() -> dict[str, Any]:
    """The checked-in ``api-info.json`` (what the CLI builds its commands from when no
    app is running)."""
    return json.loads(API_INFO_PATH.read_text(encoding="utf-8"))


def main(check: bool = False) -> int:
    info = export_api_info()
    info_text = json.dumps(info, indent=1) + "\n"
    api_text = render_api(info)
    if check:
        ok = True
        if not API_INFO_PATH.exists() or API_INFO_PATH.read_text(encoding="utf-8") != info_text:
            print(f"[ERROR] {API_INFO_PATH} is stale; run tools/gen_api.py")
            ok = False
        if not API_MODULE_PATH.exists() or API_MODULE_PATH.read_text(encoding="utf-8") != api_text:
            print(f"[ERROR] {API_MODULE_PATH} is stale; run tools/gen_api.py")
            ok = False
        if ok:
            print("[OK] generated SDK is up to date")
        return 0 if ok else 1
    API_INFO_PATH.write_text(info_text, encoding="utf-8")
    API_MODULE_PATH.write_text(api_text, encoding="utf-8")
    print(f"[OK] wrote {API_INFO_PATH} ({len(info['commands'])} commands)")
    print(f"[OK] wrote {API_MODULE_PATH}")
    return 0
