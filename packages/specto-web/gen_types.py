"""Generate TypeScript declarations for the web views from ``api-info.json`` (HLD M2:
"TypeScript bridge types generated for web views").

    uv run python packages/specto-web/gen_types.py            # write types/specto-api.d.ts
    uv run python packages/specto-web/gen_types.py --check    # exit 1 when it is stale

``tools/gen_api.py`` runs this after the SDK generation (and ``--check`` checks both).
Output: ``types/specto-api.d.ts``, an ambient ``SpectoApi`` namespace with one
``Args``/``Result`` interface per command, a ``CommandMap`` keyed by command name,
``PortType`` / ``LinkKind`` / ``ViewType`` / ``DataKind`` unions, per-view
``ViewStates`` (from the manifests' defaults) and the ``ThemeTokens`` interface (from
``specto_app.theme.theme_for_web``). ``types/specto.d.ts`` (hand-written) types the
``window.Specto`` bridge and the notifications against it; pages opt in with
``// @ts-check`` and ``npm run typecheck`` (tsc, devDependency) verifies them.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
OUT = HERE / "types" / "specto-api.d.ts"
HEADER = (
    "// GENERATED by packages/specto-web/gen_types.py from api-info.json. Do not edit.\n"
    "// Ambient declarations: every web page sees `SpectoApi.*` without an import.\n"
)


def api_info() -> dict[str, Any]:
    from specto_sdk.generate import API_INFO_PATH

    return json.loads(Path(API_INFO_PATH).read_text(encoding="utf-8"))


def app_view_manifests() -> list[dict[str, Any]]:
    """View types the app registers itself (image, markdown, map); core's ``api-info``
    only knows the built-ins. Best effort: an app without Qt yields nothing."""
    try:
        from specto_app.views import factories
    except Exception:  # pragma: no cover - headless CI without PySide6
        return []
    out: list[dict[str, Any]] = []
    for f in factories():
        plugin = getattr(f, "plugin", None)
        if plugin is None:
            continue
        out.extend(v.model_dump() for v in plugin.views)
    return out


def theme_token_names() -> list[str]:
    try:
        from specto_app.theme import theme_for_web

        return sorted(theme_for_web())
    except Exception:  # pragma: no cover
        return []


# -- json schema -> ts --------------------------------------------------------------------


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", name) if p)


def quote(v: Any) -> str:
    return json.dumps(v)


class Emitter:
    def __init__(self) -> None:
        self.named: dict[str, str] = {}  # interface name -> body (ordered)

    def ts(self, schema: dict[str, Any], defs: dict[str, Any], *, hint: str = "") -> str:
        if not schema:
            return "unknown"
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            target = defs.get(name, {})
            if target.get("type", "object") == "object" and "properties" in target:
                self.interface(pascal(name), target, defs)
                return pascal(name)
            return self.ts(target, defs, hint=name)
        if "enum" in schema:
            return " | ".join(quote(v) for v in schema["enum"])
        if "const" in schema:
            return quote(schema["const"])
        if "anyOf" in schema or "oneOf" in schema:
            parts: list[str] = []
            for alt in schema.get("anyOf") or schema.get("oneOf") or []:
                t = self.ts(alt, defs, hint=hint)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts) or "unknown"
        t = schema.get("type")
        if isinstance(t, list):
            return " | ".join(self.ts({**schema, "type": x}, defs, hint=hint) for x in t)
        if t == "string":
            return "string"
        if t in ("integer", "number"):
            return "number"
        if t == "boolean":
            return "boolean"
        if t == "null":
            return "null"
        if t == "array":
            inner = self.ts(schema.get("items") or {}, defs, hint=hint)
            return f"({inner})[]" if " | " in inner else f"{inner}[]"
        if t == "object" or "properties" in schema:
            if "properties" in schema:
                if hint:
                    self.interface(hint, schema, defs)
                    return hint
                return self.inline(schema, defs)
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return f"Record<string, {self.ts(extra, defs)}>"
            return "Record<string, unknown>"
        return "unknown"

    def fields(self, schema: dict[str, Any], defs: dict[str, Any], indent: str) -> list[str]:
        required = set(schema.get("required") or [])
        lines: list[str] = []
        for prop, ps in (schema.get("properties") or {}).items():
            doc = ps.get("description")
            if doc or "default" in ps:
                bits = [doc] if doc else []
                if "default" in ps:
                    bits.append(f"default: {json.dumps(ps['default'])}")
                lines.append(f"{indent}/** {' '.join(bits)} */")
            opt = "" if prop in required else "?"
            key = prop if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", prop) else quote(prop)
            lines.append(f"{indent}{key}{opt}: {self.ts(ps, defs)};")
        extra = schema.get("additionalProperties")
        if extra is True or isinstance(extra, dict):
            inner = self.ts(extra, defs) if isinstance(extra, dict) else "unknown"
            lines.append(f"{indent}[key: string]: {inner};")
        return lines

    def inline(self, schema: dict[str, Any], defs: dict[str, Any]) -> str:
        return "{ " + " ".join(s.strip() for s in self.fields(schema, defs, "")) + " }"

    def interface(self, name: str, schema: dict[str, Any], defs: dict[str, Any]) -> None:
        if name in self.named:
            return
        self.named[name] = ""  # reserve (recursion guard)
        body = "\n".join(self.fields(schema, defs, "    "))
        doc = schema.get("description")
        head = f"  /** {doc} */\n" if doc else ""
        self.named[name] = f"{head}  interface {name} {{\n{body}\n  }}"


# -- render ------------------------------------------------------------------------------


def render(info: dict[str, Any], app_views: list[dict[str, Any]], tokens: list[str]) -> str:
    em = Emitter()
    cmd_map: list[str] = []
    for cmd in info["commands"]:
        name = cmd["name"]
        base = pascal(name)
        args_schema = cmd.get("args_schema") or {}
        res_schema = cmd.get("result_schema") or {}
        em.interface(base + "Args", args_schema, args_schema.get("$defs", {}))
        em.interface(base + "Result", res_schema, res_schema.get("$defs", {}))
        flags = []
        for k in ("read_only", "destructive"):
            if k in cmd:
                flags.append(f"{k}: {json.dumps(cmd[k])}")
        doc = (cmd.get("doc") or "").replace("*/", "* /")
        cmd_map.append(
            f"    /** {doc} ({', '.join(flags)}; scope {cmd.get('scope', 'project')}) */\n"
            f"    {quote(name)}: {{ args: {base}Args; result: {base}Result }};"
        )

    views = {v["type"]: v for v in info.get("view_types", [])}
    for v in app_views:
        views.setdefault(v["type"], v)
    view_states: list[str] = []
    for vtype in sorted(views):
        v = views[vtype]
        schema = v.get("state_schema") or {}
        if not schema.get("properties"):
            # derive a loose shape from the defaults
            props = {}
            for k, d in (v.get("defaults") or {}).items():
                if isinstance(d, bool):
                    props[k] = {"type": "boolean"}
                elif isinstance(d, int | float):
                    props[k] = {"type": "number"}
                elif isinstance(d, str):
                    props[k] = {"type": "string"}
                elif isinstance(d, list):
                    props[k] = {"type": "array", "items": {}}
                elif isinstance(d, dict):
                    props[k] = {"type": "object", "additionalProperties": True}
                else:
                    props[k] = {}  # None: unknown until a value is written
                props[k]["default"] = d
            schema = {"type": "object", "properties": props, "additionalProperties": True}
        iface = pascal(vtype) + "State"
        em.interface(iface, schema, schema.get("$defs", {}))
        accepts = ", ".join(v.get("accepts") or []) or "nothing"
        view_states.append(
            f"    /** {v.get('label', vtype)}: accepts {accepts};"
            f" host {v.get('host', 'quick')} */\n    {quote(vtype)}: {iface};"
        )

    def union(values: list[str]) -> str:
        return " | ".join(quote(v) for v in values) or "never"

    port_types = [p["type"] for p in info.get("port_types", [])]
    link_kinds = [k["kind"] for k in info.get("link_kinds", [])]
    lines = [HEADER, "declare namespace SpectoApi {"]
    lines.append(f"  type ApiLevel = {json.dumps(info.get('api_level', 1))};")
    lines.append(f"  type SchemaVersion = {json.dumps(info.get('schema_version', 1))};")
    lines.append(f"  type Effect = {union(info.get('effects', []))};")
    lines.append(f"  type DataKind = {union(info.get('data_kinds', []))};")
    lines.append(f"  type ViewType = {union(sorted(views))};")
    lines.append(f"  type PortType = {union(port_types)};")
    lines.append(f"  type LinkKind = {union(link_kinds)};")
    lines.append("  type CommandName = keyof CommandMap;")
    lines.append("")
    lines.extend(em.named.values())
    lines.append("")
    lines.append("  interface CommandMap {\n" + "\n".join(cmd_map) + "\n  }")
    lines.append("")
    lines.append("  interface ViewStates {\n" + "\n".join(view_states) + "\n  }")
    lines.append("")
    tok = "\n".join(f"    {quote(t)}: string;" for t in tokens)
    lines.append("  /** specto_app.theme.theme_for_web(): CSS variable names without `--` */")
    lines.append("  interface ThemeTokens {\n" + tok + "\n  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> str:
    return render(api_info(), app_view_manifests(), theme_token_names())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify types/specto-api.d.ts is current")
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print(f"[ERROR] {OUT} is stale; run packages/specto-web/gen_types.py")
            return 1
        print(f"[OK] {OUT.name} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"[OK] wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
