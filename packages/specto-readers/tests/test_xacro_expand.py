def test_a_changed_include_needs_approve_again(tmp_path: Path):
    inc = _write(tmp_path / "part.xacro", '<robot><link name="part"/></robot>')
    root = _write(tmp_path / "a.xacro", _robot('<xacro:include filename="part.xacro"/>'))
    approvals = Approvals(root, inc)
    out = expand_xacro(root, find_package=_no_packages, trusted=approvals)
    assert '<link name="part"/>' in out.urdf
    _write(inc, '<robot><link name="changed"/></robot>')
    with pytest.raises(XacroNeedsApproval, match=r"include part\.xacro is not approved") as e:
        expand_xacro(root, find_package=_no_packages, trusted=approvals)
    assert e.value.path == str(inc.resolve()) and e.value.role == "include"


def test_the_approve_gesture_on_that_root_accepts_and_lists_what_it_reads(tmp_path: Path):
    inc = _write(tmp_path / "sub" / "part.xacro", '<robot><link name="part"/></robot>')
    known = _write(tmp_path / "sub" / "known.xacro", '<robot><link name="known"/></robot>')
    root = _write(
        tmp_path / "a.xacro",
        _robot(
            '<xacro:include filename="sub/part.xacro"/><xacro:include filename="sub/known.xacro"/>'
        ),
    )
    # the user approved the file they opened; what it reads comes with that click
    out = expand_xacro(
        root,
        find_package=_no_packages,
        trusted=Approvals(root, known),
        approved_root_sha=_approval(root),
    )
    assert '<link name="part"/>' in out.urdf
    # what the host records and shows: the root's approval and each newly trusted file
    assert out.accepted == {str(root.resolve()): _approval(root), str(inc.resolve()): _sha(inc)}
    # an approval of another root's hash accepts nothing here
    with pytest.raises(XacroNeedsApproval):
        expand_xacro(
            root, find_package=_no_packages, trusted=Approvals(root), approved_root_sha="0" * 64
        )
    # and the root itself is never accepted that way
    with pytest.raises(XacroNeedsApproval):
        expand_xacro(
            root, find_package=_no_packages, trusted=Approvals(), approved_root_sha=_approval(root)
        )


def test_yaml_is_gated_like_an_include(tmp_path: Path):
    import yaml

    data = _write(tmp_path / "limits.yaml", "elbow: !degrees 90\n")
    root = _write(
        tmp_path / "a.xacro",
        _robot(
            '<xacro:property name="lim" value="${xacro.load_yaml(\'limits.yaml\')}"/>'
            '<link name="l${lim.elbow}"/>'
        ),
    )
    with pytest.raises(XacroNeedsApproval, match=r"its YAML file limits\.yaml is not approved"):
        expand_xacro(root, find_package=_no_packages, trusted=Approvals(root))
    out = expand_xacro(root, find_package=_no_packages, trusted=Approvals(root, data))
    assert '<link name="l1.5707963' in out.urdf
    assert out.files[str(data.resolve())] == _sha(data)
    # xacro's unit tags do not stay on the shared loader
    assert "!degrees" not in yaml.SafeLoader.yaml_constructors


def test_includes_nest_and_missing_ones_fail_unless_optional(tmp_path: Path):
    deep = _write(tmp_path / "b" / "deep.xacro", '<robot><link name="deep"/></robot>')
    mid = _write(
        tmp_path / "b" / "mid.xacro",
        f'<robot {XNS}><xacro:include filename="deep.xacro"/><link name="mid"/></robot>',
    )
    root = _write(tmp_path / "a.xacro", _robot('<xacro:include filename="b/mid.xacro"/>'))
    out = expand_xacro(root, find_package=_no_packages, trusted=Approvals(root, mid, deep))
    assert '<link name="deep"/>' in out.urdf and '<link name="mid"/>' in out.urdf
    assert set(out.files) == {str(p.resolve()) for p in (root, mid, deep)}

    gone = _write(tmp_path / "gone.xacro", _robot('<xacro:include filename="nothere.xacro"/>'))
    with pytest.raises(XacroError, match=r"nothere\.xacro"):
        expand_xacro(gone, find_package=_no_packages, trusted=Approvals(gone))
    opt = _write(
        tmp_path / "opt.xacro",
        _robot('<xacro:include filename="nothere.xacro" optional="true"/><link name="o"/>'),
    )
    out = expand_xacro(opt, find_package=_no_packages, trusted=Approvals(opt))
    assert '<link name="o"/>' in out.urdf


def test_reads_are_confined_by_default(tmp_path: Path):
    project = tmp_path / "project"
    outside = _write(tmp_path / "elsewhere" / "x.xacro", '<robot><link name="x"/></robot>')
    pkg = tmp_path / "ros" / "desc"
    part = _write(pkg / "part.xacro", '<robot><link name="part"/></robot>')
    sneaky = _write(
        project / "robots" / "a.xacro",
        _robot('<xacro:include filename="../../elsewhere/x.xacro"/>'),
    )
    trusted = Approvals(sneaky, outside, part)
    with pytest.raises(XacroError, match=r"x\.xacro is outside the project"):
        expand_xacro(sneaky, find_package=_no_packages, trusted=trusted)
    with pytest.raises(XacroError, match="outside"):
        expand_xacro(sneaky, find_package=_no_packages, trusted=trusted, roots=[project])
    # the opt-out (tests only): the trust gate alone decides
    out = expand_xacro(sneaky, find_package=_no_packages, trusted=trusted, confine=False)
    assert '<link name="x"/>' in out.urdf
    # a package the resolver found is allowed, and so is the project
    sibling = _write(project / "shared" / "s.xacro", '<robot><link name="s"/></robot>')
    viafind = _write(
        project / "robots" / "b.xacro",
        _robot(
            '<xacro:include filename="$(find desc)/part.xacro"/>'
            '<xacro:include filename="../shared/s.xacro"/>'
        ),
    )
    out = expand_xacro(
        viafind,
        find_package={"desc": str(pkg)}.get,
        trusted=Approvals(viafind, part, sibling),
        roots=[project],
    )
    assert '<link name="part"/>' in out.urdf and '<link name="s"/>' in out.urdf


def _link_dir(link: Path, target: Path) -> None:
    if os.name == "nt":
        subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(link), str(target)],
            check=True,
            capture_output=True,
        )
    else:
        link.symlink_to(target, target_is_directory=True)


def test_a_link_out_of_the_project_is_refused_by_where_it_lands(tmp_path: Path):
    project = tmp_path / "project"
    outside = _write(tmp_path / "elsewhere" / "x.xacro", '<robot><link name="x"/></robot>')
    project.mkdir()
    _link_dir(project / "linked", outside.parent)
    root = _write(project / "a.xacro", _robot('<xacro:include filename="linked/x.xacro"/>'))
    with pytest.raises(XacroError, match="outside"):
        expand_xacro(
            root, find_package=_no_packages, trusted=Approvals(root, outside), roots=[project]
        )
    (project / "linked").rmdir() if os.name == "nt" else (project / "linked").unlink()


def test_xacro_reads_files_only_through_the_bare_open():
    """The gate shadows ``open`` in xacro's module; a xacro release that reads through
    io.open, os.open, codecs or pathlib would bypass it (the pin is below 2.2)."""
    import inspect
    import re

    import xacro
    from xacro import cli, color, substitution_args, xmlutils

    for mod in (xacro, cli, color, substitution_args, xmlutils):
        src = inspect.getsource(mod)
        assert not re.search(
            r"\b(io|os|codecs)\.open\b|pathlib|read_text\(|read_bytes\(|fdopen", src
        ), mod.__name__
    assert "f = open(filename)" in inspect.getsource(xacro.load_yaml)
    assert "open(os.path.join(root_dir, filename))" in inspect.getsource(xacro.parse)


