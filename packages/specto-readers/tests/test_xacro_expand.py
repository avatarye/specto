def test_xacro_is_left_as_it_was(tmp_path: Path):
    import xacro
    import yaml
    from xacro import substitution_args

    def state():
        return (
            substitution_args._eval_find,
            substitution_args._eval_dict["find"],
            "open" in vars(xacro),
            dict(yaml.SafeLoader.yaml_constructors),
        )

    before = state()
    root = _write(tmp_path / "a.xacro", ROBOT)
    expand_xacro(root, find_package=_no_packages, trusted=Approvals(root))
    with pytest.raises(XacroNeedsApproval):
        expand_xacro(root, find_package=_no_packages, trusted=Approvals())
    assert state() == before


def _alive(pid: int) -> bool:
    if os.name == "nt":
        import ctypes

        k32 = ctypes.windll.kernel32
        h = k32.OpenProcess(0x1000, False, pid)  # PROCESS_QUERY_LIMITED_INFORMATION
        if not h:
            return False
        code = ctypes.c_ulong()
        k32.GetExitCodeProcess(h, ctypes.byref(code))
        k32.CloseHandle(h)
        return code.value == 259  # STILL_ACTIVE
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def test_a_timeout_kills_the_child_and_what_it_started(tmp_path: Path):
    from specto_readers.xacro_expand import run_child

    pidfile = tmp_path / "grandchild.pid"
    script = (
        "import subprocess, sys, time\n"
        "p = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])\n"
        f"open(r'{pidfile}', 'w').write(str(p.pid))\n"
        "time.sleep(60)\n"
    )
    run = run_child([sys.executable, "-c", script], b"", timeout=3.0)
    assert run.timed_out
    pid = int(pidfile.read_text())
    deadline = time.monotonic() + 10
    while _alive(pid) and time.monotonic() < deadline:
        time.sleep(0.2)
    assert not _alive(pid)


def test_output_past_the_cap_fails_the_run():
    from specto_readers.xacro_expand import run_child

    script = "import sys; sys.stdout.write('x' * 300000); sys.stdout.flush()"
    run = run_child([sys.executable, "-c", script], b"", timeout=30.0, out_cap=100000)
    assert run.over_cap == "stdout"
    ok = run_child([sys.executable, "-c", script], b"", timeout=30.0)
    assert ok.over_cap is None and len(ok.stdout) == 300000


def test_expansion_runs_in_its_own_process_never_in_a_pool_worker(tmp_path: Path):
    from readers_helpers import has_module

    from specto_core.python_links import TrustStore
    from specto_readers import PoolJobManager
    from specto_readers.xacro_expand import submit_xacro

    pkg = tmp_path / "desc"
    _write(pkg / "part.xacro", '<robot><link name="part"/></robot>')
    root = _write(
        tmp_path / "a.xacro",
        _robot('<xacro:include filename="$(find desc)/part.xacro"/><link name="$(arg base)"/>'),
    )
    store = TrustStore(tmp_path / "trusted.json")
    find = {"desc": str(pkg)}.get
    args = {"base": "base_link"}
    with PoolJobManager(workers=1) as pool:
        job = submit_xacro(pool, root, find, store.approved, args=args)
        assert pool.wait([job], 60.0), job.error
        assert job.kind == "xacro"
        pending = job.result["needs_approval"]
        assert pending["path"] == str(root.resolve()) and pending["args"] == args
        assert pending["sha256"] == _approval(root, args)
        assert "urdf" not in job.result
        # the user's Approve: the root's approval goes into the store, what it reads along
        store.approve(pending["sha256"], path=str(root))
        job = submit_xacro(
            pool,
            root,
            find,
            store.approved,
            args=args,
            approved_root_sha=pending["sha256"],
            roots=[tmp_path],
        )
        assert pool.wait([job], 60.0), job.error
        assert job.message == "xacro expanded"
        assert '<link name="part"/>' in job.result["urdf"]
        assert '<link name="base_link"/>' in job.result["urdf"]
        assert str((pkg / "part.xacro").resolve()) in job.result["accepted"]
        # the worker never imported xacro: the expansion ran in a child of its own
        probe = pool.submit("t", has_module, "xacro")
        assert pool.wait([probe], 60.0) and probe.result is False
        bad = _write(tmp_path / "bad.xacro", _robot('<link name="${nope}"/>'))
        store.approve(_approval(bad), path=str(bad))
        job = submit_xacro(pool, bad, find, store.approved)
        assert pool.wait([job], 60.0)
        assert job.state == "failed" and "nope" in (job.error or "")
