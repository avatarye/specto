def test_xacro_is_left_as_it_was(tmp_path: Path):
    import xacro
    import yaml
    from xacro import substitution_args as sa

    def state():
        return (
            sa._eval_find,
            sa._env,
            sa._optenv,
            sa._eval_env,
            sa._eval_optenv,
            sa._dirname,
            sa._eval_dirname,
            "eval" in vars(sa),
            xacro.eval_extension,
            xacro.glob,
            {k: sa._eval_dict[k] for k in ("find", "env", "optenv")},
            "open" in vars(xacro),
            dict(yaml.SafeLoader.yaml_constructors),
        )

    before = state()
    root = _write(tmp_path / "a.xacro", ROBOT)
    expand_xacro(root, find_package=_no_packages, trusted=Approvals(root))
    with pytest.raises(XacroNeedsApproval):
        expand_xacro(root, find_package=_no_packages, trusted=Approvals())
    assert state() == before


def test_expansion_runs_in_its_own_process_never_in_a_pool_worker(tmp_path: Path):
    from readers_helpers import has_module

    from specto_core.python_links import TrustStore
    from specto_readers import PoolJobManager
    from specto_readers.xacro_expand import submit_xacro

    pkg = tmp_path / "desc"
    _write(pkg / "part.xacro", '<robot><link name="part"/></robot>')
    root = _write(
        tmp_path / "a.xacro",
        _robot('<xacro:include filename="$(find desc)/part.xacro"/><link name="$(arg base)"/>'),
    )
    store = TrustStore(tmp_path / "trusted.json")
    find = {"desc": str(pkg)}.get
    args = {"base": "base_link"}
    with PoolJobManager(workers=1) as pool:
        job = submit_xacro(pool, root, find, store.approved, args=args)
        assert pool.wait([job], 60.0), job.error
        assert job.kind == "xacro"
        pending = job.result["needs_approval"]
        assert pending["path"] == str(root.resolve()) and pending["args"] == args
        assert pending["sha256"] == _approval(root, args)
        assert "urdf" not in job.result
        # the user's Approve: the root's approval goes into the store
        store.approve(pending["sha256"], path=str(root))

        def run():
            job = submit_xacro(
                pool,
                root,
                find,
                store.approved,
                args=args,
                approved_root_sha=pending["sha256"],
                roots=[tmp_path],
            )
            assert pool.wait([job], 60.0), job.error
            return job

        # the package folder is shown and approved on its own, then the files come along
        package = run().result["needs_approval"]
        assert package["role"] == "package" and package["package"] == "desc"
        store.approve(package["sha256"], path=package["path"])
        job = run()
        assert job.message == "xacro expanded"
        assert '<link name="part"/>' in job.result["urdf"]
        assert '<link name="base_link"/>' in job.result["urdf"]
        assert str((pkg / "part.xacro").resolve()) in job.result["accepted"]
        # the worker never imported xacro: the expansion ran in a child of its own
        probe = pool.submit("t", has_module, "xacro")
        assert pool.wait([probe], 60.0) and probe.result is False
        bad = _write(tmp_path / "bad.xacro", _robot('<link name="${nope}"/>'))
        store.approve(_approval(bad), path=str(bad))
        job = submit_xacro(pool, bad, find, store.approved)
        assert pool.wait([job], 60.0)
        assert job.state == "failed" and "nope" in (job.error or "")


def _under_the_patch():
    from specto_readers import xacro_expand

    return xacro_expand._patched_xacro(
        open_=open, glob_=lambda p: [], extension=lambda t: t, find=lambda n: "x"
    )


def test_dirname_and_type_inside_eval_are_refused():
    """xacro 2.1.1's lexer ends a $(...) at its first ')', so no call can be written inside
    $(eval ...) today; the refusals hold for the eval itself all the same."""
    from xacro import substitution_args as sa

    ctx = {"arg": {}, "filename": "x.xacro"}
    with _under_the_patch():
        with pytest.raises(XacroError, match=r"\$\(dirname\) is off"):
            sa._eval("dirname()", ctx)
        assert sa._eval("max(1, round(2.6)) + len('ab') + abs(-1) + min(5, 9)", ctx) == "11"
        assert sa._eval("bool(1)", ctx) == "True"
        for name in ("type", "vars", "open"):
            with pytest.raises(NameError):
                sa._eval(f"{name}(1)", ctx)


def test_a_failure_partway_through_patching_leaves_nothing_patched(monkeypatch):
    import xacro
    from xacro import substitution_args as sa

    from specto_readers import xacro_expand

    before = (xacro.eval_extension, vars(xacro).get("open"), sa._dirname, dict(sa._eval_dict))

    def boom(*_):
        raise RuntimeError("partway")

    monkeypatch.setattr(xacro_expand, "_eval_builtins", boom)  # fails after the first puts
    with pytest.raises(RuntimeError, match="partway"), _under_the_patch():
        pass
    assert (
        xacro.eval_extension,
        vars(xacro).get("open"),
        sa._dirname,
        dict(sa._eval_dict),
    ) == before


def test_xacro_task_runs_the_child_in_the_fixed_folder_with_a_minimal_environment(
    tmp_path: Path, monkeypatch
):
    from specto_core.children import ChildRun, minimal_env
    from specto_readers import xacro_expand

    seen: dict = {}

    def fake_run_child(cmd, request, **kw):
        seen.update(kw)
        return ChildRun(
            b'{"urdf": "<robot/>", "files": {}, "accepted": {}, "warnings": []}\n', b"", 0
        )

    monkeypatch.setenv("SPECTO_TEST_SECRET", "x")
    monkeypatch.setattr(xacro_expand, "run_child", fake_run_child)
    out = xacro_expand.xacro_task(
        str(tmp_path / "a.xacro"), _no_packages, Approvals(), {}, None, [], lambda f, m: None
    )
    assert out["urdf"] == "<robot/>"
    folder = Path(seen["cwd"])
    assert folder == Path(xacro_expand.tempfile.gettempdir()) / "specto-xacro" and folder.is_dir()
    assert seen["env"] == minimal_env() and "SPECTO_TEST_SECRET" not in seen["env"]
